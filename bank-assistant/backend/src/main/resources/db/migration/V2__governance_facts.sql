-- Phase 3.7 / Slice A — governed business facts.
--
-- Business figures (profit margins, coverage ratios, fees, contact numbers…)
-- live here and NOWHERE in a prompt string. The Python agent reads this table
-- (albaraka.facts.build_db_facts) when it assembles an answer; staff edit it via
-- /api/admin/facts. Every change is copied to business_facts_audit so the
-- regulator can see who set which figure, when, and why.
--
-- domain / fact_type values mirror the agent's enums (albaraka.core.enums.Domain)
-- and are validated by the Java service, not by a CHECK, so adding a domain is a
-- code + data change rather than a migration.

CREATE TABLE public.business_facts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain      varchar(40)  NOT NULL,
    fact_key    varchar(120) NOT NULL,
    fact_value  text         NOT NULL,
    fact_type   varchar(40)  NOT NULL,
    topic       varchar(120),
    language    varchar(5)   NOT NULL DEFAULT 'fr',
    source      varchar(512),
    active      boolean      NOT NULL DEFAULT true,
    valid_from  date,
    updated_by  varchar(255),
    updated_at  timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT business_facts_domain_key_uk UNIQUE (domain, fact_key)
);

CREATE INDEX business_facts_domain_active_idx ON public.business_facts (domain, active);

CREATE TABLE public.business_facts_audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fact_id     bigint       NOT NULL,
    domain      varchar(40)  NOT NULL,
    fact_key    varchar(120) NOT NULL,
    action      varchar(20)  NOT NULL,   -- CREATE | UPDATE | DEACTIVATE | REACTIVATE
    old_value   text,
    new_value   text,
    reason      varchar(512),
    changed_by  varchar(255),
    changed_at  timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX business_facts_audit_fact_idx ON public.business_facts_audit (fact_id, changed_at);

