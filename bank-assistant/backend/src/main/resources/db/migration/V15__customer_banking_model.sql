ALTER TABLE public.cartes ADD COLUMN IF NOT EXISTS categorie VARCHAR(16) NOT NULL DEFAULT 'DEBIT';
ALTER TABLE public.cartes ADD COLUMN IF NOT EXISTS statut VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE public.cartes ADD COLUMN IF NOT EXISTS plafond_retrait NUMERIC(12, 3) NOT NULL DEFAULT 400;
ALTER TABLE public.cartes ADD COLUMN IF NOT EXISTS date_emission DATE;

DO $$ BEGIN
    ALTER TABLE public.cartes ADD CONSTRAINT cartes_categorie_check
        CHECK (categorie IN ('DEBIT', 'CREDIT', 'PREPAID', 'PREMIUM'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: cartes_categorie_check already exists';
END $$;

DO $$ BEGIN
    ALTER TABLE public.cartes ADD CONSTRAINT cartes_statut_check
        CHECK (statut IN ('ACTIVE', 'BLOQUEE', 'OPPOSITION', 'EXPIREE'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: cartes_statut_check already exists';
END $$;

-- `reseau` is an existing free-text column, so it is normalised BEFORE a constraint is
-- attached: a constraint that fails on legacy rows means the application never boots.
-- Case and stray spaces are the realistic leftovers; a blank network becomes the
-- default the application itself writes.
UPDATE public.cartes SET reseau = upper(btrim(reseau)) WHERE reseau IS NOT NULL AND reseau <> upper(btrim(reseau));
UPDATE public.cartes SET reseau = 'MASTERCARD' WHERE reseau IS NULL OR btrim(reseau) = '';

DO $$ BEGIN
    ALTER TABLE public.cartes ADD CONSTRAINT cartes_reseau_check
        CHECK (reseau IN ('CIB', 'VISA', 'MASTERCARD', 'AMEX'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: cartes_reseau_check already exists';
END $$;

