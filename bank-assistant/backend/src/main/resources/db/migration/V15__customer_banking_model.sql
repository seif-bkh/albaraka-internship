-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Customer identity and relationship (KYC / branch / segmentation)
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS cin VARCHAR(20);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS situation_professionnelle VARCHAR(60);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS employeur VARCHAR(160);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS revenu_mensuel NUMERIC(14, 3);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS agence_id BIGINT REFERENCES public.agences(id);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS statut_kyc VARCHAR(20) NOT NULL DEFAULT 'VALIDE';
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS niveau_risque VARCHAR(20) NOT NULL DEFAULT 'FAIBLE';
