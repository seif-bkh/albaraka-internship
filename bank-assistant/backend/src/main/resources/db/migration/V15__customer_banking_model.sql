ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS contrepartie VARCHAR(160);
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS statut VARCHAR(20) NOT NULL DEFAULT 'COMPTABILISEE';

DO $$ BEGIN
    ALTER TABLE public.transactions ADD CONSTRAINT transactions_statut_check
        CHECK (statut IN ('EN_ATTENTE', 'COMPTABILISEE', 'REJETEE'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: transactions_statut_check already exists';
END $$;

CREATE INDEX IF NOT EXISTS idx_transactions_valeur ON public.transactions (compte_id, date_valeur DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. Standing beneficiaries ("mes bénéficiaires")
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.beneficiaires (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    nom         VARCHAR(160) NOT NULL,
    rib         VARCHAR(40),
    banque      VARCHAR(160),
    pays        VARCHAR(80) NOT NULL DEFAULT 'TN',
    type        VARCHAR(20) NOT NULL DEFAULT 'VIREMENT',
    actif       BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT beneficiaires_type_check CHECK (type IN ('VIREMENT', 'PRELEVEMENT', 'INTERNE'))
);
CREATE INDEX IF NOT EXISTS idx_beneficiaires_client ON public.beneficiaires (client_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 7. Financings (Islamic products, as a Tunisian Islamic bank books them)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.financements (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id             BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    reference             VARCHAR(32) NOT NULL UNIQUE,
    produit               VARCHAR(24) NOT NULL,
    objet                 VARCHAR(200),
    montant_finance       NUMERIC(14, 3) NOT NULL,
    apport                NUMERIC(14, 3) NOT NULL DEFAULT 0,
    marge_taux            NUMERIC(6, 3),
    duree_mois            INTEGER NOT NULL,
    echeance_mensuelle    NUMERIC(14, 3),
    capital_restant       NUMERIC(14, 3),
    date_debut            DATE NOT NULL,
    date_fin              DATE,
    prochaine_echeance    DATE,
    statut                VARCHAR(20) NOT NULL DEFAULT 'EN_COURS',
    agence_id             BIGINT REFERENCES public.agences(id),
    CONSTRAINT financements_produit_check
        CHECK (produit IN ('MOURABAHA', 'IJARA', 'MOUCHARAKA', 'MOUDARABA', 'SALAM', 'ISTISNA')),
    CONSTRAINT financements_statut_check
        CHECK (statut IN ('DEMANDE', 'EN_COURS', 'EN_RETARD', 'CLOTURE', 'REJETE'))
);
CREATE INDEX IF NOT EXISTS idx_financements_client ON public.financements (client_id, statut);

COMMENT ON TABLE public.financements IS
    'Financing contracts (Islamic products). Read-only from the app: the core banking system is the writer.';
COMMENT ON COLUMN public.comptes.solde_disponible IS
    'Available balance as the core banking system reports it (solde − holds). NULL means "same as solde".';
