DO $$ BEGIN
    ALTER TABLE public.clients ADD CONSTRAINT clients_kyc_check
        CHECK (statut_kyc IN ('EN_COURS', 'VALIDE', 'A_REVALIDER', 'REJETE'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: clients_kyc_check already exists';
END $$;

DO $$ BEGIN
    ALTER TABLE public.clients ADD CONSTRAINT clients_risque_check
        CHECK (niveau_risque IN ('FAIBLE', 'MOYEN', 'ELEVE'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: clients_risque_check already exists';
END $$;

CREATE INDEX IF NOT EXISTS idx_clients_agence ON public.clients (agence_id);

-- A customer is never a staff member: the only value stored here is the marker
-- role. Staff identities live in `users`, whose role column references the role
-- catalogue. This is the database-level half of "roles belong to staff".
DO $$ BEGIN
    ALTER TABLE public.clients ADD CONSTRAINT clients_role_utilisateur_only
        CHECK (role = 'UTILISATEUR');
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: clients_role_utilisateur_only already exists';
END $$;

-- The catalogue half: a role that is not a staff role must be the client marker.
-- Creating a "client manager" style role is still allowed — it just has to be a
-- staff role, which is what the admin screens assign to bank employees.
DO $$ BEGIN
    ALTER TABLE public.admin_roles ADD CONSTRAINT admin_roles_staff_only
        CHECK (is_staff OR code = 'UTILISATEUR');
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: admin_roles_staff_only already exists';
END $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Accounts: status, RIB, available balance, authorised overdraft
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.comptes ADD COLUMN IF NOT EXISTS statut VARCHAR(20) NOT NULL DEFAULT 'ACTIF';
ALTER TABLE public.comptes ADD COLUMN IF NOT EXISTS rib VARCHAR(24);
ALTER TABLE public.comptes ADD COLUMN IF NOT EXISTS solde_disponible NUMERIC(14, 3);
ALTER TABLE public.comptes ADD COLUMN IF NOT EXISTS decouvert_autorise NUMERIC(14, 3) NOT NULL DEFAULT 0;
ALTER TABLE public.comptes ADD COLUMN IF NOT EXISTS date_cloture TIMESTAMP;

DO $$ BEGIN
    ALTER TABLE public.comptes ADD CONSTRAINT comptes_statut_check
        CHECK (statut IN ('ACTIF', 'BLOQUE', 'CLOTURE'));
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V15: comptes_statut_check already exists';
END $$;

-- The old constraint is dropped BEFORE the rows are renamed: renaming a row while the
-- old vocabulary is still enforced fails on any database that already holds an
-- ÉPARGNE or a DEPOT account (every database that ran the demo seed).
ALTER TABLE public.comptes DROP CONSTRAINT IF EXISTS comptes_type_check;

-- Existing rows keep their meaning under the new vocabulary.
UPDATE public.comptes SET type = 'COMPTE_EPARGNE'          WHERE type = 'EPARGNE';
UPDATE public.comptes SET type = 'DEPOT_INVESTISSEMENT'   WHERE type = 'DEPOT';

ALTER TABLE public.comptes ADD CONSTRAINT comptes_type_check
    CHECK (type IN ('COMPTE_COURANT', 'COMPTE_EPARGNE', 'DEPOT_INVESTISSEMENT',
                    'COMPTE_DEVISES', 'COMPTE_PROFESSIONNEL'));

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Cards: category, network, status, withdrawal limit
