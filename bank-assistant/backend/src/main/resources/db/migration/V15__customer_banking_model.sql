-- V15 — Customer banking model (retail / Islamic banking conventions).
--
-- Two decisions this migration enforces in the schema, not only in services:
--
--   1. Roles belong to staff. `admin_roles` may only carry a non-staff row for the
--      client marker role (`UTILISATEUR`), and `clients.role` is pinned to it. A
--      customer therefore cannot be given a staff role even by a direct UPDATE.
--   2. Customer data is shaped like a core-banking extract rather than a demo
--      table: branch, KYC state, risk grade, account status, RIB, available
--      balance, card category/limits, value dates and channels on movements, plus
--      standing beneficiaries and financing contracts (Mourabaha, Ijara, …).
--
-- Naming follows what Tunisian and international retail banks use (IBAN, RIB,
-- value date, available balance, KYC, murabaha), so a data team can map these
-- tables onto a real core-banking extract without a translation layer.
--
-- Additive and idempotent: no column is dropped, no row is destroyed. The two
-- account-type renames (EPARGNE → COMPTE_EPARGNE, DEPOT → DEPOT_INVESTISSEMENT)
-- are in-place UPDATEs before the check constraint is widened.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Branches (reference data — the app never edits them)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.agences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(16)  NOT NULL UNIQUE,
    nom         VARCHAR(120) NOT NULL,
    ville       VARCHAR(120) NOT NULL,
    adresse     VARCHAR(255),
    telephone   VARCHAR(32),
    actif       BOOLEAN NOT NULL DEFAULT TRUE
);

