-- V8 — Client portal: profile fields, demo banking data and conversation ownership.
--
-- The `clients` table previously held only identity (email/password/nom/prenom).
-- The client portal needs a real profile, demo banking products (comptes /
-- cartes / transactions) and the link between a conversation and the account
-- that had it, so the portal can show the client's own history.
--
-- All statements are additive and idempotent: safe on a fresh database (after
-- V1) and on an existing one. No existing column is dropped or retyped.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. clients: profile extension
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS telephone        VARCHAR(32);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS adresse          VARCHAR(255);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS ville            VARCHAR(120);
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS date_naissance   DATE;
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS langue_preferee  VARCHAR(8) DEFAULT 'fr';
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS segment          VARCHAR(32)
    CONSTRAINT clients_segment_check
    CHECK (segment IS NULL OR segment IN ('PARTICULIER', 'PROFESSIONNEL', 'ENTREPRISE'));
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS reference_client VARCHAR(20);
COMMENT ON COLUMN public.clients.reference_client IS 'Business-facing client reference (unique), assigned on first profile read if absent.';

-- Unique reference once populated (partial index: NULLs allowed during transition).
CREATE UNIQUE INDEX IF NOT EXISTS ux_clients_reference_client
    ON public.clients (reference_client)
    WHERE reference_client IS NOT NULL;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. conversations: optional owner (anonymous chat stays anonymous)
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.conversations ADD COLUMN IF NOT EXISTS client_id BIGINT;
DO $$ BEGIN
    ALTER TABLE public.conversations
        ADD CONSTRAINT fk_conversations_client
        FOREIGN KEY (client_id) REFERENCES public.clients(id) ON DELETE SET NULL;
EXCEPTION WHEN duplicate_object THEN RAISE NOTICE 'V8: fk_conversations_client already exists';
END $$;
CREATE INDEX IF NOT EXISTS idx_conversations_client ON public.conversations (client_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Demo banking products (client portal — seeded data, production would be
--    fed by the core banking system; the portal is strictly read-only on them).
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.comptes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    libelle         VARCHAR(120) NOT NULL,
    type            VARCHAR(32)  NOT NULL,
    iban            VARCHAR(40)  NOT NULL UNIQUE,
    devise          VARCHAR(8)   NOT NULL DEFAULT 'TND',
    solde           NUMERIC(14, 3) NOT NULL DEFAULT 0,
    date_ouverture  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT comptes_type_check CHECK (type IN ('COMPTE_COURANT', 'EPARGNE', 'DEPOT'))
);
CREATE INDEX IF NOT EXISTS idx_comptes_client ON public.comptes (client_id);

CREATE TABLE IF NOT EXISTS public.cartes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id           BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    compte_id           BIGINT REFERENCES public.comptes(id) ON DELETE SET NULL,
    type                VARCHAR(40) NOT NULL,
    reseau              VARCHAR(20) NOT NULL DEFAULT 'MASTERCARD',
    porteur             VARCHAR(24) NOT NULL,
    expiration          VARCHAR(7)  NOT NULL,
    plafond_journalier  NUMERIC(12, 3) NOT NULL DEFAULT 1000,
    bloque              BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_cartes_client ON public.cartes (client_id);

CREATE TABLE IF NOT EXISTS public.transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id       BIGINT NOT NULL REFERENCES public.comptes(id) ON DELETE CASCADE,
    date_operation  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    libelle         VARCHAR(160) NOT NULL,
    categorie       VARCHAR(40),
    montant         NUMERIC(14, 3) NOT NULL,
    devise          VARCHAR(8) NOT NULL DEFAULT 'TND'
);
CREATE INDEX IF NOT EXISTS idx_transactions_compte ON public.transactions (compte_id, date_operation DESC);
