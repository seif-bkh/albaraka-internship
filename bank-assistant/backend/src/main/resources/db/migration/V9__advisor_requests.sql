-- V9 — Advisor requests (rendez-vous / rappel conseiller).
--
-- The portal-home quick tiles "Rendez-vous" and "Conseiller" persist client
-- requests here. They are REQUESTS, not bookings: status starts at
-- EN_ATTENTE and staff confirm by phone (24 h notice pattern, see
-- docs/UIUX_RESEARCH.md §2). kind discriminates the two flows:
--   APPOINTMENT — motif + meeting method (+ optional branch/date/time)
--   CALLBACK    — telephone + preferred time + message
--
-- No branch catalogue exists in governed data yet (P1 deferred), so
-- preferred_branch is free text.

CREATE TABLE public.advisor_requests (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id         bigint NOT NULL REFERENCES public.clients(id),
    kind              varchar(20)  NOT NULL
        CONSTRAINT advisor_requests_kind_check CHECK (kind IN ('APPOINTMENT', 'CALLBACK')),
    status            varchar(20)  NOT NULL DEFAULT 'EN_ATTENTE'
        CONSTRAINT advisor_requests_status_check
        CHECK (status IN ('EN_ATTENTE', 'CONFIRMEE', 'ANNULEE')),
    motif             varchar(200),
    meeting_method    varchar(20)
        CONSTRAINT advisor_requests_method_check
        CHECK (meeting_method IS NULL OR meeting_method IN ('AGENCE', 'TELEPHONE')),
    preferred_branch  varchar(200),
    preferred_date    date,
    preferred_time    varchar(5),
    telephone         varchar(32),
    message           text,
    created_at        timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_advisor_requests_client ON public.advisor_requests (client_id, created_at DESC);
CREATE INDEX idx_advisor_requests_status ON public.advisor_requests (status, created_at);
