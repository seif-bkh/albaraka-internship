-- V10 — News items (actualités) for the portal home and the public landing.
--
-- Admins manage them from /admin/news; only rows with active = true and a
-- publish date in the past are served to clients (GET /api/news/active).
-- An optional external link points at the full article (the bank website).

CREATE TABLE public.news_items (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(200) NOT NULL,
    body          text         NOT NULL,
    external_link varchar(500),
    published_at  date         NOT NULL,
    active        boolean      NOT NULL DEFAULT true,
    created_at    timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at    timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_news_items_public ON public.news_items (active, published_at DESC);
