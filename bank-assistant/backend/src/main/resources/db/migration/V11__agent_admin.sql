-- ============================================================
-- V11 — Assistant administration.
--
-- Where the external RAG engine lives (the "Assistant IA / Santé &
-- diagnostic" screen), and the journal of every change made to the
-- assistant's configuration from the back-office.
--
-- No seed row on purpose: "no endpoint row" means "use the deployed default"
-- (RAGLAB_URL). An untouched deployment therefore behaves exactly as
-- configured, and the first admin edit is both stored and traced.
--
-- Secrets are never stored here: keys live in the service that owns them.
-- ============================================================

CREATE TABLE public.agent_endpoint (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Base URL of the RAG service, e.g. http://10.20.30.40:8000 (no trailing slash).
    url        varchar(300) NOT NULL,
    -- Why the admin changed it (mandatory at the API level, kept for the journal).
    reason     varchar(512),
    updated_by varchar(255),
    updated_at timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE TABLE public.agent_admin_audit (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ENDPOINT_SET, ENDPOINT_CLEARED, … one row per state-changing action.
    action     varchar(40)  NOT NULL,
    target     varchar(120),
    detail     varchar(600),
    reason     varchar(512),
    actor      varchar(255),
    outcome    varchar(20)  NOT NULL DEFAULT 'OK',
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_agent_admin_audit_created_at ON public.agent_admin_audit (created_at DESC);
