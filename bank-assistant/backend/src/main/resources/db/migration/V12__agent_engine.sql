-- ============================================================
-- V12 — Which engine answers the customers.
--
-- One human decision at a time: a row records that an admin chose an engine,
-- who they were and why. "No row" means "the deployed default"
-- (AGENT_PROVIDER_DEFAULT), so an untouched deployment behaves exactly as
-- configured and the first switch is both stored and journalled.
--
-- The two engines are addressed elsewhere: the in-house agent by AGENT_URL, the
-- external RAG service by agent_endpoint / RAGLAB_URL.
-- ============================================================

CREATE TABLE public.agent_engine (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider   varchar(20)  NOT NULL
        CONSTRAINT agent_engine_provider_check CHECK (provider IN ('LEGACY', 'RAGLAB')),
    reason     varchar(512),
    updated_by varchar(255),
    updated_at timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_agent_engine_updated_at ON public.agent_engine (updated_at DESC);
