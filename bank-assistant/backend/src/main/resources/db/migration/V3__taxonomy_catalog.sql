-- Phase 3.7 / Slice B — taxonomy exemplars + catalog releases.
--
-- The classifier scores customer messages against a *frozen* catalog of
-- exemplar phrasings. Staff curate the exemplars here; nothing the assistant
-- learns from chats ever lands in this table (AGENTS/PLAN: no self-improvement).
-- Editing an exemplar changes nothing live until an admin SEALS a release:
-- catalog_release pins the exemplar set under a new version and the backend
-- publishes that version to Redis (agent:catalog:active); the agent then loads
-- the rows frozen under that version. Old releases stay readable for pinning.

CREATE TABLE public.catalog_category (
    domain      varchar(40)  NOT NULL,
    intent      varchar(40)  NOT NULL,
    label_fr    varchar(255) NOT NULL,
    PRIMARY KEY (domain, intent)
);

CREATE TABLE public.catalog_exemplar (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain      varchar(40)  NOT NULL,
    intent      varchar(40)  NOT NULL,
    text        varchar(512) NOT NULL,
    language    varchar(5)   NOT NULL DEFAULT 'fr',
    topic       varchar(120),
    slots       varchar(255),                 -- comma-separated slot names
    active      boolean      NOT NULL DEFAULT true,
    updated_by  varchar(255),
    updated_at  timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT catalog_exemplar_text_uk UNIQUE (domain, intent, language, text)
);

CREATE INDEX catalog_exemplar_active_idx ON public.catalog_exemplar (active);

CREATE TABLE public.catalog_release (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         varchar(40)  NOT NULL UNIQUE,
    sealed_by       varchar(255),
    sealed_at       timestamp(6) without time zone NOT NULL DEFAULT now(),
    exemplar_count  integer      NOT NULL,
    note            varchar(512)
);

-- Frozen copy of the exemplars as they were at seal time, per version.
CREATE TABLE public.catalog_release_exemplar (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id  bigint       NOT NULL REFERENCES public.catalog_release (id),
    domain      varchar(40)  NOT NULL,
    intent      varchar(40)  NOT NULL,
    text        varchar(512) NOT NULL,
    language    varchar(5)   NOT NULL,
    topic       varchar(120),
    slots       varchar(255)
);

CREATE INDEX catalog_release_exemplar_release_idx ON public.catalog_release_exemplar (release_id);

