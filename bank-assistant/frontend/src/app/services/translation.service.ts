const DICTS: Record<Lang, Dict> = { fr, en, ar };

@Injectable({ providedIn: 'root' })
export class TranslationService {
  readonly lang = signal<Lang>('fr');

  /** Set the active language (fr | ar | en). */
  setLang(lang: string): void {
    const l: Lang = (lang === 'ar' || lang === 'en' || lang === 'fr') ? lang : 'fr';
    this.lang.set(l);
  }

  /** Translation of a key in the active language. */
  t(key: string): string {
    const dict = DICTS[this.lang()];
    return (dict && dict[key]) ?? fr[key] ?? key;
  }

}

@Pipe({
  name: 'translate',
  pure: false,
  standalone: true,
})
export class TranslatePipe implements PipeTransform {
  constructor(private i18n: TranslationService) {}
  transform(key: string): string {
    return this.i18n.t(key);
  }
}
